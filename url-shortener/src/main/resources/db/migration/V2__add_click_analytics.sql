-- Brownfield: click analytics. Additive and backward compatible
-- (new column has a default; new table only), so it is safe to roll forward.
ALTER TABLE short_url ADD COLUMN click_count BIGINT NOT NULL DEFAULT 0;

CREATE TABLE click_event (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    short_url_id  BIGINT NOT NULL REFERENCES short_url (id) ON DELETE CASCADE,
    clicked_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    referrer      VARCHAR(512),
    user_agent    VARCHAR(512)
);

CREATE INDEX idx_click_event_url_time ON click_event (short_url_id, clicked_at);
